def emit(out_dir):
    rows = []
    for code in range(128):
        gl = F.get(code, ("......",) * 8)
        for r in gl:
            b = 0
            for x, ch in enumerate(r):
                if ch == '#':
                    b |= 0x80 >> x
            rows.append(b)
    with open(os.path.join(out_dir, 'gen_font.c'), 'w') as f:
        f.write("/* generated by tools/mkfont.py - do not edit */\n")
        f.write('#include "gba.h"\n\n')
        f.write("const u8 g_font6x8[128*8] = {\n")
        for i in range(0, len(rows), 16):
            f.write("    " + ",".join("0x%02X" % v for v in rows[i:i+16]) + ",\n")
        f.write("};\n")
    with open(os.path.join(out_dir, 'gen_font.h'), 'w') as f:
        f.write("/* generated by tools/mkfont.py */\n#ifndef GEN_FONT_H\n#define GEN_FONT_H\n")
        f.write('#include "gba.h"\nextern const u8 g_font6x8[128*8];\n')
        f.write("#define FONT_W 6\n#define FONT_H 8\n#endif\n")
    print("mkfont: %d glyphs" % len(F))

if __name__ == '__main__':
    emit(sys.argv[1] if len(sys.argv) > 1 else 'src/gen')
